// Reads the supplied master artwork and writes its geometry as data, so the
// video animates the real logo rather than a redrawing of it (guidelines p.02:
// "Do use supplied master artwork", "Do not redraw the logo").
//
//   node scripts/extract-logo.mjs
//
// Every <path> keeps its id from the master file and inherits the attributes of
// the <g> it sits in, which is how the SVG itself resolves them.
import { readFileSync, writeFileSync } from 'node:fs'

const source = new URL('../public/brand/scrapal-logo.svg', import.meta.url)
const target = new URL('../src/brand/logo-data.ts', import.meta.url)
const svg = readFileSync(source, 'utf8').replace(/<!--[\s\S]*?-->/g, '')

const INHERITED = ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'opacity']
const attrs = (text) => Object.fromEntries([...text.matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]))

const stack = []
const parts = []
for (const [, close, tag, body, selfClose] of svg.matchAll(/<(\/?)([\w:]+)([^>]*?)(\/?)>/g)) {
  if (tag !== 'g' && tag !== 'path') continue
  if (close) { stack.pop(); continue }
  const own = attrs(body)
  if (tag === 'g') {
    if (!selfClose) stack.push({ id: own.id, ...own })
    continue
  }
  // Only the logo's own geometry: defs carry no paths in the master file.
  const inherited = {}
  for (const group of stack) for (const key of INHERITED) if (group[key] != null) inherited[key] = group[key]
  const style = Object.fromEntries((own.style ?? '').split(';').filter(Boolean).map((rule) => rule.split(':').map((s) => s.trim())))
  const group = stack.at(-1)
  parts.push({
    id: own.id,
    group: group?.id ?? null,
    d: own.d.replace(/\s+/g, ' ').trim(),
    transform: group?.transform ?? null,
    fill: style.fill ?? own.fill ?? inherited.fill ?? null,
    stroke: own.stroke ?? inherited.stroke ?? null,
    strokeWidth: Number(own['stroke-width'] ?? inherited['stroke-width'] ?? 0) || null,
    linecap: own['stroke-linecap'] ?? inherited['stroke-linecap'] ?? null,
    linejoin: own['stroke-linejoin'] ?? inherited['stroke-linejoin'] ?? null,
    opacity: Number(own.opacity ?? 1),
  })
}

const out = `// Generated by scripts/extract-logo.mjs from public/brand/scrapal-logo.svg.
// Do not edit by hand — change the master artwork and re-run the script.

export type LogoPart = {
  id: string
  group: string | null
  d: string
  transform: string | null
  fill: string | null
  stroke: string | null
  strokeWidth: number | null
  linecap: 'round' | 'butt' | 'square' | null
  linejoin: 'round' | 'miter' | 'bevel' | null
  opacity: number
}

export const LOGO_VIEWBOX = { width: 1200, height: 360 } as const
/** The icon-only crop, from public/brand/scrapal-icon.svg. */
export const ICON_VIEWBOX = { x: 34, y: 18, width: 292, height: 330 } as const

export const LOGO_PARTS: LogoPart[] = ${JSON.stringify(parts, null, 2)}
`
writeFileSync(target, out)
console.log(`Wrote ${parts.length} logo parts to ${target.pathname}`)
